package org.example.demofx;

public class GestiondeDescuento {

        public static void main(String[] args) {
            int j = 0;
            int i = 10;
            while (i != 0) {
                j = i;
                while (j != 0) {
                    System.out.print(j);
                    j = j - 1;
                }
                i = i - 1;
            }
        }
    
}

